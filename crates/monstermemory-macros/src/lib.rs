//! # `MonsterMemory` derive macros
//!
//! Compile-time schema generation for `MonsterMemory`, an Attraqualia project developed by halnos.
//!
//! Applications normally import these derives through `monstermemory::prelude`. [`Table`] defines
//! record metadata and typed index queries; [`Database`] connects one or more record types to a
//! shared MVCC engine, snapshots, and write transactions. Generated code refers to the
//! `monstermemory` crate by that name, so the facade must be available under that name in the
//! consuming crate.
//!
//! The runnable end-to-end examples belong to the `monstermemory` facade, which supplies the
//! runtime types used by generated code. The attribute fragments below describe syntax rather
//! than standalone Rust programs. This proc-macro crate has no runtime dependency on the facade.

#![forbid(unsafe_code)]

extern crate proc_macro;

mod database;
mod table;

use proc_macro::TokenStream;

/// Derives table metadata, extractors, and typed secondary-index methods.
///
/// Apply this derive to a concrete struct with named fields and exactly one `#[primary_key]`.
/// The record must implement `Clone + Send + Sync + 'static`; its primary key must also implement
/// `Debug + Eq + Hash`. Generic parameters and lifetimes are rejected. Indexed field types must
/// implement `monstermemory::IndexValue`; lookup arguments use `monstermemory::Lookup`.
///
/// # Attributes and generated queries
///
/// | Placement | Attribute | Effect |
/// | --- | --- | --- |
/// | Struct | `#[table(name = "users")]` | Override the logical table name; the default inserts underscores before uppercase letters in the record name and lowercases them. |
/// | Field | `#[primary_key]` | Select the immutable primary key; this attribute accepts no options. |
/// | Field | `#[index]` | Generate `by_<field>(&key)`, a lazy iterator over exact matches. |
/// | Field | `#[index(unique)]` | Generate `by_<field>(&key)`, returning an optional record handle. |
/// | Field | `#[index(range)]` or `#[index(ordered)]` | Generate `<field>_range(bounds)`, a lazy ordered iterator. |
/// | Field | `#[index(name = "alias")]` | Change the generated index name; combine with at most one index kind. |
/// | Struct | `#[composite_index(name = "country_age", fields(country, age), kind = "ordered")]` | Generate `by_country_age((&country, age_bounds))`, matching every field except the last exactly and ranging over the last. |
///
/// A composite index requires at least two distinct existing fields. Index names must be valid
/// Rust identifiers and unique within the table. Duplicate or colliding generated query names
/// are rejected. All query methods are provided by the generated `<Record>TableQueries` trait,
/// implemented for both live `Table<Record>` and `SnapshotTable<Record>` handles. Import that
/// trait when querying from a different module.
///
/// Unique queries return `None` for absent keys; exact and range queries return empty iterators
/// when nothing matches. Non-unique matches use logical-row order; ordered queries sort by
/// encoded index key, then logical-row order. Lazy iterators capture a root when created and keep
/// it alive until dropped, even while concurrent commits change the live table. Bounds preserve
/// `RangeBounds` inclusion and exclusion; composite prefix matching uses whole field values,
/// not string-prefix matching.
///
/// # Diagnostics
///
/// Unsupported input shapes, missing or repeated primary keys, invalid attributes, and invalid
/// index definitions produce compile-time diagnostics. Missing record/key trait implementations
/// are reported by the Rust type checker. No database is created by this derive alone; combine
/// it with [`Database`] on a separate database struct.
#[proc_macro_derive(Table, attributes(table, primary_key, index, composite_index))]
pub fn derive_table(input: TokenStream) -> TokenStream {
    table::expand(input.into())
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

/// Derives constructors, snapshots, transactions, and a typed bulk loader.
///
/// Apply this derive to a concrete, nonempty struct containing only named `Table<Record>` fields.
/// Each record type must implement the schema generated by [`Table`]. Repeating the same record
/// type spelling in multiple fields is rejected. The struct cannot have generic parameters or
/// lifetimes. Generated companion types inherit the database struct's visibility; their table
/// fields are public.
///
/// For a database named `AppDb`, this creates `AppDbSnapshot`, `AppDbWriteTransaction`,
/// `AppDbBulkLoader`, and `AppDbBuilder`. The database exposes `memory`, `builder`, `snapshot`,
/// `write`, `retrying_write`, `bulk_load`, `metrics`, and `schema_fingerprint`.
///
/// # Transactions and validation
///
/// `write` calls its closure once and commits staged operations across all tables atomically.
/// An error from the closure aborts publication; commit validation may reject write conflicts or
/// unique-index violations. `retrying_write` repeats the closure only after a retryable *commit*
/// error, within `RetryPolicy`'s limit. An error returned by the closure itself is propagated
/// immediately. Retried closures must tolerate repetition of any external side effects.
///
/// `#[database(validate = "validate_database")]` installs a function taking
/// `&AppDbSnapshot` and returning `monstermemory::Result<()>`. It sees the candidate root after
/// conflict and index validation and before publication. It is not called for an empty commit.
/// Validation runs while the commit gate is held: it must not try to write to, or checkpoint,
/// the same database. Snapshot isolation alone does not prevent write skew across distinct keys;
/// use validation when an invariant spans those keys.
///
/// # Persistence
///
/// `#[database(persistence)]` additionally generates `open`, `checkpoint`, and
/// `checkpoint_with_durability`. Enable the facade's `persistence` feature and implement serde
/// serialization/deserialization for every record type. `open` restores the latest complete
/// sidecar WAL image when present, otherwise the checkpoint, otherwise an empty database; it
/// installs a synchronous WAL append before later commits are published. Checkpointing a
/// memory-only database writes an image without enabling automatic WAL logging on that instance.
/// Use one live database instance per checkpoint/WAL path; there is no cross-instance file lock.
///
/// The generated fingerprint hashes the database name and the field/record type spellings. It
/// does not incorporate record fields or their serialization layout, and is not a complete
/// schema-compatibility check. Treat persisted data as tied to the application's schema and
/// this alpha version; schema migrations are not generated.
///
/// # Builder limits
///
/// The current builder rejects a zero memory budget but does not enforce a nonzero budget.
/// `snapshot_warning_after` is accepted without scheduling warnings. Monitor `metrics()` and
/// enforce application limits separately.
///
/// # Diagnostics
///
/// Invalid input shapes and unknown or repeated database options produce compile-time
/// diagnostics. Generated runtime operations report the concrete errors described on their
/// individual methods.
#[proc_macro_derive(Database, attributes(database))]
pub fn derive_database(input: TokenStream) -> TokenStream {
    database::expand(input.into())
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}
