//! Schema metadata shared by generated code and the engine.

use crate::key::IndexKey;
use std::{fmt::Debug, hash::Hash};

/// Kind of a generated secondary index.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum IndexKind {
    /// A present key maps to at most one row; duplicates fail at commit.
    Unique,
    /// One key maps to zero or more rows.
    Exact,
    /// Keys are ordered and support range scans.
    Ordered,
    /// Multiple fields are ordered lexicographically.
    CompositeOrdered,
}

impl IndexKind {
    /// Returns whether the index enforces uniqueness.
    #[must_use]
    pub const fn is_unique(self) -> bool {
        matches!(self, Self::Unique)
    }
}

/// Compile-time metadata for one generated index.
#[derive(Clone, Copy, Debug)]
pub struct IndexDefinition {
    /// Stable index name used by generated methods and diagnostics.
    pub name: &'static str,
    /// Index behavior.
    pub kind: IndexKind,
    /// Source field names in declared component order, compared lexicographically.
    pub fields: &'static [&'static str],
}

/// Compile-time metadata for a table.
#[derive(Debug)]
pub struct TableMetadata {
    /// Logical table name.
    pub name: &'static str,
    /// Rust record type name.
    pub rust_type: &'static str,
    /// Primary-key field name.
    pub primary_key: &'static str,
    /// Generated secondary indexes.
    pub indexes: &'static [IndexDefinition],
    /// Fingerprint generated from the table definition.
    ///
    /// This is schema identification material, not a cryptographic integrity check.
    pub fingerprint: u64,
}

/// Primary-key requirements for a `MonsterMemory` table.
///
/// Every type satisfying these bounds implements the trait automatically. Keys
/// must retain consistent equality and hashing while stored in a database; changing
/// a key requires deleting the old row and inserting a new one.
pub trait PrimaryKey: Clone + Debug + Eq + Hash + Send + Sync + 'static {}

impl<T> PrimaryKey for T where T: Clone + Debug + Eq + Hash + Send + Sync + 'static {}

/// Trait generated by `#[derive(Table)]`.
///
/// Prefer the derive macro from `monstermemory` to a manual implementation. A
/// manual implementation must return exactly one [`IndexKey`] per metadata index,
/// in the same order, and must keep the metadata and key encoding consistent for
/// the lifetime of the database. Incorrect implementations can panic during index
/// maintenance or produce incorrect lookup results.
///
/// Published records must be treated as immutable, including values reachable
/// through interior mutability. Changing an indexed value through a shared handle
/// bypasses index maintenance; sharing mutable state across `Clone` implementations
/// can also break snapshot isolation. Use the table write methods to replace rows.
pub trait TableSchema: Clone + Send + Sync + 'static {
    /// Primary-key type.
    type PrimaryKey: PrimaryKey;

    /// Returns an owned copy of the row's primary key.
    ///
    /// The value must not change while the row is published. An update that returns
    /// a different key is rejected with [`crate::Error::PrimaryKeyChanged`].
    fn primary_key(&self) -> Self::PrimaryKey;

    /// Extracts keys in the exact order declared by [`Self::metadata`].
    ///
    /// The returned vector length must equal `metadata().indexes.len()`. Each
    /// component must use the canonical encoding of its corresponding field.
    fn index_keys(&self) -> Vec<IndexKey>;

    /// Returns static table and index metadata.
    ///
    /// All calls for a given record type must describe the same schema.
    fn metadata() -> &'static TableMetadata;
}
